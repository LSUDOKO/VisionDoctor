"""Collect results/*/*.json into results/summary.md (tables quoted by REPORT.md)."""

from __future__ import annotations

import json

from common import RESULTS


def load(p: str) -> dict | None:  # type: ignore[type-arg]
    f = RESULTS / p
    return json.loads(f.read_text()) if f.exists() else None


def main() -> None:
    L = ["# VisionDoctor — results summary", "", "_Generated by `eval/summarize.py`; every number comes from a JSON file in `results/`._", ""]
    e1 = load("e1/detection.json")
    if e1:
        L += ["## E1 — fault detection (`results/e1/detection.json`)", "",
              f"Scans: {e1['n_scans']} on {', '.join(e1['videos'])}. Recall at severity ≥ 3: **{e1['recall_sev3plus']}** "
              f"(classic tamper baseline {e1['baseline_recall_sev3plus']}). Clean-burst alarm rate: {e1['clean_alarm_rate']} "
              f"(baseline {e1['baseline_clean_alarm_rate']}).", "",
              "| Fault | R@1 | R@2 | R@3 | R@4 | R@5 | Baseline R@3 | Precision (sev≥3) |", "|---|---|---|---|---|---|---|---|"]
        for f, d in e1["faults"].items():
            ps = d["per_severity"]
            L.append(f"| {f} | " + " | ".join(str(ps[str(s)]["recall"]) for s in range(1, 6))
                     + f" | {ps['3']['baseline_recall']} | {d['precision_sev3plus']} |")
        L.append("")
    e2 = load("e2/false_alarms.json")
    if e2:
        L += ["## E2 — false alarms on clean footage (`results/e2/false_alarms.json`)", "",
              "| Setting | Scans | False incidents / camera-day (2-scan hysteresis) | Without hysteresis |", "|---|---|---|---|"]
        for k, name in (("day", "Day footage"), ("day_night_buckets", "Day+night, luminance buckets"),
                        ("day_night_single_ref", "Day+night, single reference (ablation)")):
            p = e2.get(f"pooled_{k}")
            if p:
                L.append(f"| {name} | {p['scans']} | {p['per_cam_day_h2']} | {p['per_cam_day_h1']} |")
        L += ["", "| Video | Day h2 | Day+night buckets h2 | Single-ref h2 |", "|---|---|---|---|"]
        for v, d in e2["videos"].items():
            L.append(f"| {v} | {d['day']['false_incidents_per_cam_day_h2']} | {d['day_night_buckets']['false_incidents_per_cam_day_h2']} "
                     f"| {d['day_night_single_ref']['false_incidents_per_cam_day_h2']} |")
        L.append("")
    e3 = load("e3/impact.json")
    if e3:
        a, b = e3["agreement_cv"], e3["true_ap_drop_mot17"]
        L += ["## E3 — label-free AI-impact prediction (`results/e3/impact.json`)", "",
              f"Rows: {e3['rows']}. Leave-one-video-out Spearman ρ (predicted vs actual agreement): **{a['spearman']}** "
              f"(95% CI {a['spearman_ci95']}), MAE {a['mae']}.",
              f"Against **true** MOT17 person AP@0.5 drop ({b['groups']} fault×severity groups, held-out predictions): "
              f"Spearman ρ **{b['spearman']}** (95% CI {b['spearman_ci95']}), MAE {b['mae']}.", "",
              "| Held-out video | n | ρ | MAE |", "|---|---|---|---|"]
        L += [f"| {v} | {d['n']} | {d['spearman']} | {d['mae']} |" for v, d in a["per_video"].items()]
        L += ["", "Top features (permutation importance): " + ", ".join(
            f"{x['feature']} ({x['importance']})" for x in e3["permutation_importance_top12"][:6]), ""]
    e4 = load("e4/repair.json")
    if e4:
        L += ["## E4 — repair effectiveness (`results/e4/repair.json`)", "",
              "| Fault | Detected | Verified (of attempted) | AP clean → degraded → repaired | Accuracy recovered (95% CI) |",
              "|---|---|---|---|---|"]
        for f, d in e4.items():
            L.append(f"| {f} | {d['detected_rate']} | {d['verified_rate_of_attempted']} | {d['ap_clean_mean']} → "
                     f"{d['ap_degraded_mean']} → {d['ap_repaired_mean']} | {d['accuracy_recovered_mean']} {d['accuracy_recovered_ci95']} |")
        if e4.get("drift", {}).get("residual_rot_deg_max") is not None:
            L.append(f"\nMax residual rotation after realign: {e4['drift']['residual_rot_deg_max']}°.")
        L.append("")
    for agent in ("policy", "bedrock"):
        e5 = load(f"e5/agent_{agent}.json")
        if e5:
            L += [f"## E5 — agent quality, {agent} (`results/e5/agent_{agent}.json`)", "",
                  f"Incidents: {e5['incidents']}. Correct outcome: **{e5['correct_outcome_rate']}** (95% CI {e5['correct_ci95']}). "
                  f"Operator alerts: {e5['agent_operator_alerts']} vs {e5['alarm_only_baseline_alerts']} for alarm-only → "
                  f"workload reduction **{e5['operator_workload_reduction']}**. Auto-fixed: {e5['auto_fixed']}. "
                  f"Missed escalations: {e5['missed_escalations']}, unnecessary: {e5['unnecessary_escalations']}. "
                  f"Mean steps {e5['mean_steps']}, mean agent time {e5['mean_agent_ms']} ms, scans to detect {e5['scans_to_detect_mean']}, "
                  f"trace completeness {e5['trace_completeness']}.", "",
                  "Confusion (expected→outcome): " + ", ".join(f"{k}: {v}" for k, v in e5["confusion"].items()), ""]
    cal = load("calibration/thresholds.json")
    if cal:
        L += ["## Threshold calibration (`results/calibration/thresholds.json`)", "",
              "| Check | Metric | Clean p50 | Clean p99.5 | First band edge |", "|---|---|---|---|---|"]
        L += [f"| {c} | {d['metric']} | {d['p50']} | {d['p99_5']} | {d['first_band_edge']} |" for c, d in cal["checks"].items()]
        L.append("")
    bench = load("bench/summary.json")
    if bench:
        L += ["## Benchmark (`results/bench/summary.json`)", "", "| Config | Instance | COOL | Scans/min | p50 ms | p95 ms | $/1M scans |",
              "|---|---|---|---|---|---|---|"]
        for c, d in bench["configs"].items():
            L.append(f"| {c} | {d['instance_type'] or 'local'} | {d['is_cool']} | {d['scans_per_min']:.1f} | {d['scan_p50_ms']:.0f} | "
                     f"{d['scan_p95_ms']:.0f} | {d['usd_per_1M_scans']} |")
        L.append("")
    (RESULTS / "summary.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
